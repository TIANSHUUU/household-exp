--
-- 配套改动：租金从「结算公式里的一项」改成「每月自动生成的真实开支」。
-- 完整设计见 docs/superpowers/specs/2026-11-02-rent-as-expense-design.md
--
-- 为什么租金配置必须进数据库，不能留在 localStorage：
--
--   现在 cfg（租金金额 + 租金日）存在 localStorage 里，是**每台设备各一份**
--   的。以前无所谓——它只是个显示用的公式参数。但改成「自动生成写进数据库
--   的真实金额」之后，两台设备不一致就会出事：同一个月的租金记成多少，取决
--   于谁先打开网页。而且房租行的 id 是按日期派生的（幂等设计），**先写的那
--   个值会永久固定下来**，后打开的那台设备不会去纠正它。
--
-- 这一步必须在前端代码上线之前跑完，否则设置面板保存时会 400。
--
-- 怎么跑：Supabase 控制台 → SQL Editor → 整段粘进去 → Run
-- ════════════════════════════════════════════════════════════════════════════


-- ┌────────────────────────────────────────────────────────────────────────┐
-- │ 第 1 步：加两列                                                        │
-- │                                                                        │
-- │ numeric 而不是 float：钱不能用浮点存。                                 │
-- │ if not exists 让这段可以重复跑，不会因为已经加过而报错。               │
-- └────────────────────────────────────────────────────────────────────────┘

alter table public.cycles
  add column if not exists rent_amount numeric,
  add column if not exists rent_day    integer;


-- ┌────────────────────────────────────────────────────────────────────────┐
-- │ 第 2 步：把当前活跃账期的值填上                                        │
-- │                                                                        │
-- │ 1250 和 22 是你现在 localStorage 里的值。只填 active 那一行——历史      │
-- │ 账期不需要，它们的 transfer 是冻结值，不会再重算。                     │
-- │ where ... is null 保证重复跑不会覆盖你之后改过的数值。                 │
-- └────────────────────────────────────────────────────────────────────────┘

update public.cycles
   set rent_amount = 1250,
       rent_day    = 22
 where status = 'active'
   and rent_amount is null;


